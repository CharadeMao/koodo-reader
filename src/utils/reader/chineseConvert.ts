const S2T_MAP: Record<string, string> = {};
S2T_PAIR.forEach(([s, t]) => {
  S2T_MAP[s] = t;
});

export class ChineseConvert {
  public static convertString(str: string, mode: "s2t" | "t2s" | string): string {
    if (!str || mode !== "s2t") return str;
    let result = "";
    for (let i = 0; i < str.length; i++) {
      const char = str[i];
      result += S2T_MAP[char] || char;
    }
    return result;
  }

  public static convertIframe(doc: Document, mode: "s2t" | "t2s" | string): void {
    if (!doc || !doc.body || mode !== "s2t") return;

    const walkNode = (node: Node) => {
      if (node.nodeType === Node.TEXT_NODE) {
        if (node.nodeValue && node.nodeValue.trim().length > 0) {
          node.nodeValue = ChineseConvert.convertString(node.nodeValue, mode);
        }
      } else if (
        node.nodeType === Node.ELEMENT_NODE &&
        node.nodeName.toLowerCase() !== "script" &&
        node.nodeName.toLowerCase() !== "style"
      ) {
        node.childNodes.forEach(walkNode);
      }
    };

    walkNode(doc.body);
  }

  public static convertAllIframes(mode: "s2t" | "t2s" | string): void {
    const docs = getIframeDoc("ANY");
    docs.forEach((doc) => {
      if (doc) {
        ChineseConvert.convertIframe(doc, mode);
      }
    });
  }
}

export default ChineseConvert;
